from __future__ import annotations

import json

from application.services.card_generation.llm_schemas import WriteCardOutput
from application.services.card_generation.prompts.rules import (
    DATA_RULE,
    TRUTH_RULES,
    render_device,
)
from domain.entities.product import Product

SYSTEM = f"""Ты проверяешь тексты товара в B2B-магазине контрольно-измерительных приборов. Ищешь только два вида дефектов и ничего больше: ни стиль, ни длину, ни вкусовые правки.

{DATA_RULE}

{TRUTH_RULES}

Вид unsupported_claim: утверждение о приборе, которого нет в <device> и которое верно не для любого прибора этого класса. Например новое свойство, устройство или способ индикации, материал, стандарт, сертификат, отрасль, объект или место установки, среда, оценка качества.

Вид filler: фраза, которую можно убрать, и покупатель ничего не потеряет:
- служебная фраза: упоминание черновика, карточки, входных данных, JSON, источника сведений, того, что чего-то нет;
- вода: фраза без сведений о приборе («обеспечивает эффективную работу», «отличный выбор», «учитывают при выборе», «важно при подборе»), объяснение слов ради длины («обозначение модели служит идентификатором», «показывающий характер означает…»), совет сверить модель или маркировку при заказе;
- повтор: одно значение или одна мысль дважды внутри одного поля, в том числе один параметр в двух предложениях: сначала что он определяет, потом его значение;
- тавтология: следствие только повторяет сам параметр («класс точности задаёт погрешность, поэтому погрешность должна соответствовать классу», «среда должна входить в число таких сред»).

Не замечание:
- общие слова о классе прибора и его назначении, смысл параметра, если это верно для любого прибора этого класса;
- прямое следствие значения для покупателя: «рабочее давление должно укладываться в этот диапазон», «при другой резьбе понадобится переходник», «при подборе этот сигнал сравнивают со входом вторичного прибора»;
- несколько значений в одном предложении и разные обороты;
- роли покупателей в commercial.audience: служба КИПиА, снабжение, монтажные и сервисные организации;
- одно значение в разных полях: заголовок, описание, запросы и commercial могут повторять друг друга;
- поисковые слова вроде «купить» в search_queries.

Перед каждым unsupported_claim проверь себя: «это верно для всех приборов этого класса, в том числе других исполнений?» Если да, это не замечание. Если бывает по-разному, это замечание.

quote: короткий фрагмент проверяемого текста, скопированный символ в символ. reason: одна фраза, что не так и как исправить.
Пустой список обычный исход: большинство текстов без дефектов."""


def build_message(product: Product, draft: WriteCardOutput) -> str:
    texts = draft.model_dump(
        include={"seo_title", "seo_description", "search_queries", "commercial"}
    )
    texts_json = json.dumps(texts, ensure_ascii=False, indent=1)
    return f"""{render_device(product)}

<texts>
{texts_json}
</texts>

Проверь <texts> по сведениям из <device>."""
